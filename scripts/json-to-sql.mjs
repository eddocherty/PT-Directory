#!/usr/bin/env node
// Turn an importer-ready JSON file into plain SQL that can be pasted into the Supabase SQL editor.
// Usage: node scripts/json-to-sql.mjs data/pilot-trainers.json > pilot.sql
// Upserts by slug, never re-adds a listing whose status is 'removed', and never touches a claimed listing's details.
import { readFile } from "node:fs/promises";

const rows = JSON.parse(await readFile(process.argv[2], "utf8"));
const q = (v) => (v == null ? "null" : typeof v === "number" || typeof v === "boolean" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => (a?.length ? `array[${a.map(q).join(", ")}]::text[]` : "'{}'::text[]");
const LICENCE = {
  osm: "ODbL, © OpenStreetMap contributors; description from the business's own website",
  website: "Business details published on the trainer's own website",
};

const out = ["-- Generated by scripts/json-to-sql.mjs. Safe to run more than once.", "begin;", ""];
for (const r of rows) {
  const cols = {
    slug: q(r.slug), name: q(r.name), business_name: q(r.business_name), headline: q(r.headline), bio: q(r.bio),
    city: q(r.city), region: q(r.region), postcode_district: q(r.postcode_district),
    location: r.lat != null ? `extensions.st_setsrid(extensions.st_makepoint(${r.lng}, ${r.lat}), 4326)::extensions.geography` : "null",
    in_person: q(r.in_person ?? true), online: q(r.online ?? false), home_visits: q(r.home_visits ?? false),
    price_from: q(r.price_from), price_to: q(r.price_to), qualifications: arr(r.qualifications), years_experience: q(r.years_experience),
    website: q(r.website), email: q(r.email), phone: q(r.phone), instagram: q(r.instagram), image_url: "null",
    free_consultation: q(r.free_consultation ?? false), sports: arr(r.sports),
    source: q(r.source), source_url: q(r.source_url), source_licence: q(r.source_licence ?? LICENCE[r.source] ?? null),
    last_verified_at: "now()", is_sample: "false", status: "'published'",
  };
  const names = Object.keys(cols);
  const updates = names.filter((c) => c !== "slug" && c !== "status").map((c) => `${c} = excluded.${c}`).join(", ");
  out.push(`-- ${r.name}${r.business_name && r.business_name !== r.name ? ` (${r.business_name})` : ""}`);
  out.push(`insert into public.trainers (${names.join(", ")})`);
  out.push(`select ${names.map((c) => cols[c]).join(", ")}`);
  out.push(`where not exists (select 1 from public.trainers where slug = ${q(r.slug)} and status = 'removed')`);
  out.push(`on conflict (slug) do update set ${updates}`);
  out.push(`  where public.trainers.claimed_by is null and public.trainers.status <> 'removed';`);
  out.push(`delete from public.trainer_styles where trainer_id = (select id from public.trainers where slug = ${q(r.slug)} and claimed_by is null);`);
  out.push(`delete from public.trainer_goals where trainer_id = (select id from public.trainers where slug = ${q(r.slug)} and claimed_by is null);`);
  if (r.styles?.length) out.push(`insert into public.trainer_styles (trainer_id, style_slug) select id, s from public.trainers, unnest(${arr(r.styles)}) s where slug = ${q(r.slug)} and claimed_by is null and status = 'published' on conflict do nothing;`);
  if (r.goals?.length) out.push(`insert into public.trainer_goals (trainer_id, goal_slug) select id, g from public.trainers, unnest(${arr(r.goals)}) g where slug = ${q(r.slug)} and claimed_by is null and status = 'published' on conflict do nothing;`);
  out.push("");
}
out.push("commit;", "", `select count(*) as real_trainers from public.trainers where is_sample = false and status = 'published';`);
console.log(out.join("\n"));
